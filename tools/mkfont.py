#!/usr/bin/env python3
"""Rasterize printable ASCII from a TTF/OTF into a C header of 8-bit alpha glyphs.

usage: mkfont.py FONT OUT.h NAME:SIZE [NAME:SIZE ...]
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126


def emit(out, path, name, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    _, cap_top, _, cap_bot = font.getbbox("H")
    glyphs, px = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch)
        w, h = max(right - left, 0), max(bottom - top, 0)
        glyphs.append((len(px), w, h, left, top, round(font.getlength(ch))))
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-left, -top), ch, font=font, fill=255)
            px += im.tobytes()
    out.write(f"static const uint8_t {name}_px[{max(len(px), 1)}] = {{\n")
    for i in range(0, len(px), 32):
        out.write("\t" + ",".join(map(str, px[i:i + 32])) + ",\n")
    out.write("};\n")
    out.write(f"static const font_t {name} = {{ {size}, {ascent}, {ascent + descent}, "
              f"{cap_top}, {cap_bot - cap_top}, {name}_px, {{\n")
    for g in glyphs:
        out.write("\t{%d, %d, %d, %d, %d, %d},\n" % g)
    out.write("} };\n\n")


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    font, dest, specs = sys.argv[1], sys.argv[2], sys.argv[3:]
    with open(dest, "w") as out:
        out.write(f"/* Generated by tools/mkfont.py from {os.path.basename(font)}. Do not edit. */\n\n")
        for spec in specs:
            name, size = spec.split(":")
            emit(out, font, name, int(size))


if __name__ == "__main__":
    main()
